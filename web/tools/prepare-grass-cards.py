"""Reviewed Standard bright grass marks and EGA dots; retain native RGB only."""
from pathlib import Path
from hashlib import sha256
import json
from PIL import Image,ImageDraw
root=Path(__file__).resolve().parents[1];graphics=root/'public/graphics';out=root/'docs/grass-depth';out.mkdir(exist_ok=True)
layouts={};records=[];review=Image.new('RGB',(520,300),'#252525');draw=ImageDraw.Draw(review)
for row,name in enumerate(['Standard','PC EGA']):
 source=graphics/f'{name}-Tiles.png';sheet=Image.open(source).convert('RGBA');size=sheet.width//12
 tile=sheet.crop((0,size,size,2*size));seen=set();parts=[]
 def selected(x,y):
  r,g,b,a=tile.getpixel((x,y));return g>=85 if name=='Standard' else (r,g,b)==(0,176,0)
 for y in range(size):
  for x in range(size):
   if (x,y) in seen or not selected(x,y):continue
   q=[(x,y)];seen.add((x,y))
   for a,b in q:
    for c,d in [(a-1,b),(a+1,b),(a,b-1),(a,b+1)]:
     if 0<=c<size and 0<=d<size and (c,d) not in seen and selected(c,d):seen.add((c,d));q.append((c,d))
   parts.append(q)
 assert len(parts)<=64
 atlas=Image.new('RGBA',(64,64));cutout=Image.new('RGBA',(size,size));patches=[]
 for i,q in enumerate(parts):
  x0=min(x for x,y in q);y0=min(y for x,y in q);x1=max(x for x,y in q);y1=max(y for x,y in q);w=x1-x0+1;h=y1-y0+1
  assert w<=6 and h<=6
  ax=(i%8)*8+1;ay=(i//8)*8+1
  for x,y in q:
   colour=tile.getpixel((x,y));atlas.putpixel((ax+x-x0,ay+y-y0),colour);cutout.putpixel((x,y),colour)
  bottom=[x for x,y in q if y==y1];foot=sum(bottom)/len(bottom)+.5
  patches.append([foot/size,(y1+1)/size,w/size,h/size,ax/64,1-(ay+h)/64,w/64,h/64,(foot-x0)/w])
 target=graphics/f'{name}-GrassCards.png';atlas.save(target);layouts[name]=patches
 records.append({'set':name,'source':source.name,'sourceSha256':sha256(source.read_bytes()).hexdigest(),'atlas':target.name,'sha256':sha256(target.read_bytes()).hexdigest(),'marks':len(parts),'selection':'reviewed native green >= 85' if name=='Standard' else 'reviewed EGA grass green (0,176,0)'})
 draw.text((5,row*150+10),name,fill='white');review.paste(tile.resize((128,128),Image.Resampling.NEAREST),(160,row*150));check=Image.new('RGBA',(size,size),'#555');check=Image.alpha_composite(check,cutout);review.paste(check.resize((128,128),Image.Resampling.NEAREST),(330,row*150))
review.save(out/'review.png');(out/'manifest.json').write_text(json.dumps(records,indent=2)+'\n')
(root/'src/ui/grassLayouts.ts').write_text('// Generated by tools/prepare-grass-cards.py; native source colours only.\nexport type GrassPatch = readonly [number,number,number,number,number,number,number,number,number];\nexport const GRASS_LAYOUTS: Readonly<Record<string, readonly GrassPatch[]>> = '+json.dumps(layouts)+';\n')
