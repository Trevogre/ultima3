"""Split reviewed cutouts into native-pixel components; no source RGB/alpha changes."""
from pathlib import Path
from hashlib import sha256
import json
from PIL import Image, ImageDraw
root=Path(__file__).resolve().parents[1]
graphics=root/'public/graphics';out=root/'docs/forest-cards'
names=['Standard','Lairware','Nintendo','PC Ultima V','Apple II Color','Apple II Mono','PC EGA','PC CGA','Commodore 64']
simple=set(names[4:]);layouts={};receipts=[]
review=Image.new('RGB',(680,len(names)*145),'#252525');draw=ImageDraw.Draw(review)
def isolate(image, box):
 result=Image.new('RGBA',image.size);result.paste(image.crop(box),box[:2]);return result

def base(image):
 w,h=image.size;points=[(x,y) for y in range(h) for x in range(w) if image.getpixel((x,y))[3]]
 last=max(y for x,y in points);xs=[x for x,y in points if y==last]
 return [round((sum(xs)/len(xs)+.5)*64/w,4),round((last+1)*64/h,4)]

def components(image):
 w,h=image.size;seen=set();result=[]
 for y in range(h):
  for x in range(w):
   if (x,y) in seen or not image.getpixel((x,y))[3]:continue
   q=[(x,y)];seen.add((x,y))
   for a,b in q:
    for c,d in [(a-1,b),(a+1,b),(a,b-1),(a,b+1)]:
     if 0<=c<w and 0<=d<h and (c,d) not in seen and image.getpixel((c,d))[3]:seen.add((c,d));q.append((c,d))
   card=Image.new('RGBA',image.size)
   for a,b in q:card.putpixel((a,b),image.getpixel((a,b)))
   result.append(card)
 return result

for row,name in enumerate(names):
 forest=Image.open(graphics/f'{name}-ForestCard.png').convert('RGBA');size=forest.height
 brush_path=graphics/f'{name}-BrushCards.png';brush=Image.open(brush_path).convert('RGBA') if brush_path.exists() else None
 if name=='Standard':
  source=Image.open(graphics/'Standard-TreeCards.png').convert('RGBA')
  trees=[source.crop((i*64,0,(i+1)*64,64)) for i in range(3)]
  tree_anchors=[[20,35],[48,55],[18,63]]
 elif name=='Lairware':
  trees=components(forest);assert len(trees)==3
  tree_anchors=[[18,33],[48,53],[18,63]]
 elif name in simple:
  edges=[0,size//3,2*(size//3),size]
  trees=[isolate(forest,(0,edges[i],size,edges[i+1])) for i in range(3)]
  tree_anchors=[base(c) for c in trees]
 else:
  trees=[forest];tree_anchors=[base(forest)]
 bushes=[]
 if brush:
  if name=='Standard':bushes=[brush.crop((i*size,0,(i+1)*size,size)) for i in range(4)]
  elif name in simple:
   split=14 if name=='Apple II Color' else 13 if name=='Apple II Mono' else size//2
   boxes=[(0,0,split,size//2),(split,0,size,size//2),(0,size//2,split,size),(split,size//2,size,size)]
   bushes=[isolate(brush,box) for box in boxes]
  else:bushes=[brush]
 bush_anchors=[[16,19],[46,33],[16,50],[46,63]] if name=='Standard' else [base(c) for c in bushes]
 atlas=Image.new('RGBA',(8*size,size))
 for cards,original,start in [(trees,forest,0),(bushes,brush,4)]:
  if not cards:continue
  assert len(cards)<=4
  combined=Image.new('RGBA',(size,size))
  for i,card in enumerate(cards):
   assert card.getbbox()
   atlas.paste(card,((start+i)*size,0));combined=Image.alpha_composite(combined,card)
  if original.width==size:
   assert combined.getchannel('A').tobytes()==original.getchannel('A').tobytes(), 'Lost source alpha'
   assert all(a[:3]==b[:3] for a,b in zip(combined.getdata(),original.getdata()) if b[3]),'Changed source RGB'
 target=graphics/f'{name}-VegetationCards.png';atlas.save(target)
 layouts[name]={'trees':tree_anchors,'brush':bush_anchors}
 receipts.append({'set':name,'file':target.name,'sha256':sha256(target.read_bytes()).hexdigest(),'nativeSize':size,**layouts[name]})
 draw.text((6,row*145+10),name,fill='white')
 for col,(cards,anchors) in enumerate([(trees,tree_anchors),(bushes,bush_anchors)]):
  combined=Image.new('RGBA',(size,size))
  for card in cards:combined=Image.alpha_composite(combined,card)
  background=Image.new('RGBA',(size,size),'#777');background=Image.alpha_composite(background,combined)
  expanded=background.resize((128,128),Image.Resampling.NEAREST);d=ImageDraw.Draw(expanded)
  for x,y in anchors:
   px=x*2;py=min(127,y*2);d.line((px-3,py,px+3,py),fill='red');d.line((px,py-3,px,py+3),fill='red')
  review.paste(expanded,(200+col*200,row*145))
review.save(out/'vegetation-anchors.png')
(out/'vegetation-layouts.json').write_text(json.dumps(receipts,indent=2)+'\n')
(root/'src/ui/vegetationLayouts.ts').write_text('''// Generated by tools/prepare-vegetation-layouts.py from reviewed native cutouts.
export interface VegetationLayout {
  trees: readonly (readonly [number, number])[];
  brush: readonly (readonly [number, number])[];
}
export const VEGETATION_LAYOUTS: Readonly<Record<string, VegetationLayout>> = '''+json.dumps(layouts,indent=2)+';\n')
