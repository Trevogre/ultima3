"""Prepare the bundled CC0 VSCO sample subset. Requires Python + NumPy.
Usage: python3 web/tools/prepare-orchestra.py /path/to/downloaded-source
Source names and pinned URLs are recorded in the output manifest.
"""
import sys, wave, json, hashlib, shutil
from pathlib import Path
import numpy as np

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
out = root / 'public/music/orchestra'
out.mkdir(parents=True, exist_ok=True)
info = json.loads((source / 'sources.json').read_text())
roots = {'violin-low':55, 'violin-high':72, 'cello-bass':36, 'cello-low':60, 'cello-high':67,
         'flute-low':60, 'flute-mid':72, 'flute-high':84, 'harp-low':48, 'harp-high':72}
records = []
rate = 22050
for name, pitch in roots.items():
    path = source / (name + '.wav')
    with wave.open(str(path)) as w:
        sr, channels, width = w.getframerate(), w.getnchannels(), w.getsampwidth()
        raw = w.readframes(w.getnframes())
    if width == 3:
        a = np.frombuffer(raw, np.uint8).reshape(-1,3).astype(np.int32)
        a = a[:,0] + (a[:,1]<<8) + (a[:,2]<<16)
        a = ((a ^ 8388608) - 8388608).astype(float) / 8388608
    else:
        a = np.frombuffer(raw, '<i2').astype(float) / 32768
    a = a.reshape(-1, channels).mean(axis=1)
    audible = np.flatnonzero(np.abs(a) > np.max(np.abs(a)) * 0.005)
    start = max(0, int(audible[0]) - int(sr * 0.005))
    a = a[start:start + int(sr * 3.5)]
    # Windowed-sinc low-pass before downsampling; preserve native pitch.
    taps = np.arange(-63,64)
    cutoff = 0.45 * rate / sr
    filt = 2 * cutoff * np.sinc(2 * cutoff * taps) * np.hamming(len(taps))
    filt /= filt.sum()
    a = np.convolve(a, filt, mode='same')
    a = np.interp(np.arange(int(len(a) * rate / sr)) * sr / rate, np.arange(len(a)), a)
    a *= 0.72 / max(np.max(np.abs(a)), 1e-9)
    a[:int(rate*.005)] *= np.linspace(0,1,int(rate*.005))
    sustained = not name.startswith('harp')
    if sustained:
        a = a[:rate*3]
        fade = int(rate*.08)
        lead = a[int(rate*.8):int(rate*.8)+fade].copy()
        blend = np.linspace(0,1,fade)
        a[-fade:] = a[-fade:] * (1-blend) + lead * blend
    else:
        a[-int(rate*.12):] *= np.linspace(1,0,int(rate*.12))
    output = out / (name + '.wav')
    with wave.open(str(output),'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate)
        w.writeframes(np.round(np.clip(a,-1,1)*32767).astype('<i2').tobytes())
    records.append({'id': name, 'instrument': name.split('-')[0], 'file':name+'.wav', 'root':pitch,
        'loopStart':0.88 if sustained else 0, 'loopEnd':3 if sustained else 0,
        'source':info['paths'][name], 'sourceSha256':hashlib.sha256(path.read_bytes()).hexdigest(),
        'sha256':hashlib.sha256(output.read_bytes()).hexdigest()})
shutil.copyfile(source/'LICENSE',out/'LICENSE.txt')
shutil.copyfile(source/'Readme.txt',out/'UPSTREAM-README.txt')
(out/'manifest.json').write_text(json.dumps({'library':'VSCO 2 Community Edition','license':'CC0-1.0',
    'repository':'https://github.com/sgossner/VSCO-2-CE','revision':info['revision'],
    'processing':'Mono 22050 Hz PCM16; leading silence trimmed; peak normalized to 0.72; 3s crossfaded sustain loops or 3.5s harp with fade.',
    'samples':records},indent=2)+'\n')
specs = [{k:r[k] for k in ['id','instrument','file','root','loopStart','loopEnd']} for r in records]
(root/'src/ui/orchestraSamples.ts').write_text('// Generated by tools/prepare-orchestra.py; source provenance in public/music/orchestra/manifest.json.\nexport const ORCHESTRA_SAMPLES = '+json.dumps(specs,indent=2)+' as const;\n')
print('Bundled',len(records),'samples,',sum(p.stat().st_size for p in out.glob('*.wav')),'bytes')
